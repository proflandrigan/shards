'use strict';
// Writes the target layout. Deterministic: sorted, no timestamps. See MACROS.md section 6.
const fs = require('fs');
const path = require('path');
const YAML = require('yaml');

const pkg = require('../package.json');
const { CLAUDE_TOOL_PREFIX, CODEX_TOOL_PREFIX } = require('./render');

const REPO = path.resolve(__dirname, '..');
const DEV_MARKER = '.shards-dev';
const fwd = (p) => p.split(path.sep).join('/');
const fm = (obj) => `---\n${YAML.stringify(obj, { lineWidth: 0 }).trimEnd()}\n---\n`;
const jsonText = (o) => `${JSON.stringify(o, null, 2)}\n`;

function tomlMulti(s) { return `"""\n${s.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"')}\n"""`; }
function tomlStr(s) { return JSON.stringify(String(s)); }

function toolsOf(meta) {
  const t = meta && meta.tools;
  const list = Array.isArray(t) ? t : String(t || '').split(',').map((x) => x.trim()).filter(Boolean);
  return list.filter((x) => x !== 'Task'); // consults cannot nest; TODO(E5.3)
}

function skillBody(a, persona, target) {
  const modes = a.doc.activation || [];
  const mode = modes.includes('switch') ? 'switch' : 'consult';
  const pre = target === 'claude' ? CLAUDE_TOOL_PREFIX : target === 'codex' ? CODEX_TOOL_PREFIX : '';
  return `${persona.trimEnd()}\n\n---\n\nRuntime: call \`${pre}activate\`(agent="${a.id}", mode="${mode}") to start, then load each phase with \`${pre}load_phase\`(agent="${a.id}", n, track?). Content for this agent lives under \`content/agents/${a.id}/\`.\n`;
}

function agentsSkill(target) {
  const pre = target === 'claude' ? CLAUDE_TOOL_PREFIX : target === 'codex' ? CODEX_TOOL_PREFIX : '';
  const description = 'List the available Shards agents with role, activation modes and description.';
  const body = `# Shards agents\n\nCall \`${pre}list_agents\`() (no arguments). Print the result as a table with the columns id, role, activation, description (one row per agent, activation joined with commas). If an entry has an \`error\` field, show its id with the error in the description column. Do not call any other tool and do not start an agent.\n`;
  return fm({ name: 'agents', description }) + '\n' + body;
}

function emitTarget({ target, core, rendered, agentBodies, report, dev, outDir }) {
  const out = new Map();
  for (const [rel, data] of rendered) out.set(rel, data);
  out.set('size-report.json', jsonText(report));

  for (const [id, a] of [...core.agents].sort((x, y) => (x[0] < y[0] ? -1 : 1))) {
    const res = agentBodies.get(id) || { meta: null, body: '' };
    const description = a.doc.description;
    const persona = res.body;
    out.set(`skills/${id}/SKILL.md`, fm({ name: id, description }) + '\n' + skillBody(a, persona, target));
    if (target === 'claude') {
      const tools = toolsOf(res.meta);
      const head = { name: id, description };
      if (tools.length) head.tools = tools.join(', ');
      out.set(`agents/${id}.md`, `${fm(head)}\n${persona}`);
    } else if (target === 'codex') {
      out.set(`.codex/agents/${id}.toml`, `name = ${tomlStr(id)}\ndescription = ${tomlStr(description)}\ndeveloper_instructions = ${tomlMulti(persona)}\n`);
    }
  }

  out.set('skills/agents/SKILL.md', agentsSkill(target));

  if (dev) {
    out.set(DEV_MARKER, 'generated by `shards build --dev`; removed by `shards uninstall-dev`\n');
    const hooksDir = fwd(path.join(REPO, 'hooks'));
    const runtime = fwd(path.join(REPO, 'runtime', 'server.js'));
    if (target === 'claude') {
      out.set('.claude-plugin/plugin.json', jsonText({ name: 'shards', version: pkg.version, description: pkg.description }));
      // Project root comes from the host env (verified: plugin MCP env expands ${CLAUDE_PROJECT_DIR}); runtime reads SHARDS_PROJECT_ROOT.
      out.set('.mcp.json', jsonText({ mcpServers: { shards: { command: 'node', args: [runtime], env: { SHARDS_PROJECT_ROOT: '${CLAUDE_PROJECT_DIR}' } } } }));
      // Dev: hook commands point at the repo's own hooks dir so edits apply without a rebuild.
      const hooks = fs.readFileSync(path.join(REPO, 'hooks', 'claude-code.hooks.json'), 'utf8').split('${CLAUDE_PLUGIN_ROOT}/hooks/').join(`${hooksDir}/`);
      out.set('hooks/hooks.json', hooks);
    } else if (target === 'codex') {
      out.set('.codex-plugin/plugin.json', jsonText({ name: 'shards', version: pkg.version, description: pkg.description, skills: './skills/' })); // docs-only, UNVERIFIED
      // TODO(E8.3): per-tool approval_mode for gate_advance / gate_force_close (Milestone B).
      out.set('.codex/config.toml', `[mcp_servers.shards]\ncommand = "node"\nargs = [${tomlStr(runtime)}]\n`);
      out.set('.codex/hooks.json', fs.readFileSync(path.join(REPO, 'hooks', 'codex.hooks.json'), 'utf8').split('{{SHARDS_HOOKS_DIR}}').join(hooksDir));
    }
  }
  // Non-dev packaging: TODO(E7.4/E8.3) plugin manifest, published MCP entry and hook shims are not emitted yet.

  const written = [];
  for (const rel of [...out.keys()].sort()) {
    const full = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, out.get(rel));
    written.push(rel);
  }
  return written;
}

module.exports = { emitTarget, DEV_MARKER, REPO };
